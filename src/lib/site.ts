/**
 * Canonical origin for metadata, Open Graph URLs and the sitemap.
 *
 * `NEXT_PUBLIC_SITE_URL` is the explicit, authoritative setting. When it is
 * absent the build falls back to the hosting provider's own production URL so
 * that a deployed site never ships `localhost` in its Open Graph tags — a
 * localhost `og:image` is the reason a shared link shows no picture at all.
 */
const configuredUrl =
  process.env.NEXT_PUBLIC_SITE_URL ??
  (process.env.VERCEL_PROJECT_PRODUCTION_URL
    ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
    : process.env.VERCEL_URL
      ? `https://${process.env.VERCEL_URL}`
      : undefined);

export const siteUrl = (configuredUrl ?? "http://localhost:3000").replace(/\/$/, "");

export function absoluteUrl(path = "/"): string {
  return `${siteUrl}${path.startsWith("/") ? path : `/${path}`}`;
}

